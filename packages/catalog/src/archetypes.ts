// The screen archetypes the catalog speaks, and registry.archetypes.json: for
// each archetype, the recipes that name it and the general ones (`*`) that fit
// any screen. A speccer that has assigned a screen its archetype reads one
// entry instead of scoring every recipe; its `behaviour` names the recipes
// (recipeKind behaviour) every screen of that archetype is expected to use. The list is OpenDesign's 30
// (fluxnative-opendesign, mobile-design/src/contracts/screen-spec.ts) plus the
// five AI ones, the same list fluxbuilder-template's check_templates.py holds.

import { join } from 'node:path';
import { PACKAGE_ROOT } from './emit.ts';
import { renderRegistry, type Registry, type RegistryEntry } from './registry.ts';

export const AI_ARCHETYPES = ['ai-chat', 'ai-generate', 'ai-scan', 'ai-voice', 'ai-insight'] as const;

export const ARCHETYPES = [
  'onboarding', 'authentication', 'profile', 'settings', 'guided-tours', 'permissions',
  'notifications', 'feedback', 'error-empty', 'loading', 'home-feeds', 'content-detail',
  'search', 'filter-sort', 'crud', 'select-input', 'social', 'community', 'messaging',
  'media-playback', 'media-capture', 'paywall', 'cart-checkout', 'orders-billing',
  'promotions', 'maps', 'dashboards', 'utilities', 'learning', 'other',
  ...AI_ARCHETYPES,
] as const;

export type Archetype = (typeof ARCHETYPES)[number];

/** In a registry entry's `archetypes`, `*` means the recipe fits any screen. */
export const ANY_ARCHETYPE = '*';

export function isArchetype(value: string): value is Archetype {
  return (ARCHETYPES as readonly string[]).includes(value);
}

/** 2: each entry gains `behaviour`. */
export const ARCHETYPE_MAP_VERSION = 2;
export const ARCHETYPE_MAP_FILE = join(PACKAGE_ROOT, 'registry.archetypes.json');

/** One archetype's recipes, names only; most evidence first, then by name. */
export interface ArchetypeEntry {
  /** Recipes whose `archetypes` name this one. */
  recipes: string[];
  /** Recipes marked `*` (any screen) that are not already in `recipes`. */
  general: string[];
  /** The names in `recipes`, then `general`, whose `recipeKind` is `behaviour`: what every screen of this archetype is expected to use, never copy. */
  behaviour: string[];
}

export interface ArchetypeMap {
  $comment: string;
  mapVersion: number;
  archetypes: Record<Archetype, ArchetypeEntry>;
}

/** Hand-written copies in the template catalog first, then categories, then name (code-point order, so the bytes do not depend on the locale). */
function byEvidence(a: RegistryEntry, b: RegistryEntry): number {
  const templates = (b.evidence.templates ?? 0) - (a.evidence.templates ?? 0);
  if (templates !== 0) return templates;
  const categories = (b.evidence.categories ?? 0) - (a.evidence.categories ?? 0);
  if (categories !== 0) return categories;
  return a.name < b.name ? -1 : a.name > b.name ? 1 : 0;
}

/** Every `archetypes[]` value in the registry that is neither on ARCHETYPES nor `*`, as `Component: value`. */
export function unknownArchetypes(registry: Registry = renderRegistry()): string[] {
  return registry.components.flatMap((c) => c.archetypes.filter((a) => a !== ANY_ARCHETYPE && !isArchetype(a)).map((a) => `${c.name}: ${a}`));
}

export function renderArchetypeMap(registry: Registry = renderRegistry()): ArchetypeMap {
  const unknown = unknownArchetypes(registry);
  if (unknown.length) throw new Error(`registry.meta.json names archetypes that are not on ARCHETYPES (src/archetypes.ts): ${unknown.join(', ')}`);
  const sorted = [...registry.components].sort(byEvidence);
  const general = sorted.filter((c) => c.archetypes.includes(ANY_ARCHETYPE));
  const archetypes = {} as Record<Archetype, ArchetypeEntry>;
  for (const archetype of ARCHETYPES) {
    const own = sorted.filter((c) => c.archetypes.includes(archetype));
    const recipes = own.map((c) => c.name);
    const rest = general.filter((c) => !recipes.includes(c.name));
    const behaviour = [...own, ...rest].filter((c) => c.recipeKind === 'behaviour').map((c) => c.name);
    archetypes[archetype] = { recipes, general: rest.map((c) => c.name), behaviour };
  }
  return {
    $comment: 'Generated by `fluxnative-catalog registry` from registry.json; do not edit. Per archetype: the recipes that name it and the general (`*`) ones, most evidence first; `behaviour` is those of recipeKind behaviour, which every screen of the archetype is expected to use.',
    mapVersion: ARCHETYPE_MAP_VERSION,
    archetypes,
  };
}

export function renderArchetypeMapJson(registry?: Registry): string {
  return `${JSON.stringify(renderArchetypeMap(registry), null, 2)}\n`;
}
